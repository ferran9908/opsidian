export const MAX_NOTE_LENGTH = 2_000_000;
export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
export interface NoteSnapshot {
  content: string;
  location: string;
  assets: Record<string, string>;
}
export interface ImportedImage {
  path: string;
  url: string;
}
export interface NotebookBridge {
  load(): Promise<NoteSnapshot>;
  save(content: string): Promise<void>;
  importImage(): Promise<ImportedImage | null>;
}
export function validateContent(value: unknown): asserts value is string {
  if (typeof value !== 'string' || value.length > MAX_NOTE_LENGTH) {
    throw new Error('This prototype supports notes up to 2 million characters.');
  }
}
export function imageMarkdown(path: string): string {
  // Paths are generated by the host, not arbitrary user filenames.
  if (!/^attachments\/[a-zA-Z0-9-]+\.(png|jpg|jpeg|gif|webp)$/.test(path)) {
    throw new Error('Invalid attachment path');
  }
  return `\n![Attached image](${path})\n`;
}
